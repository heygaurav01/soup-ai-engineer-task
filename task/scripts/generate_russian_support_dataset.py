def generate_pairs(target_count: int = 500) -> List[Dict[str, str]]:
    """Generate domain-diverse customer support preference pairs in Russian."""
    pairs = []
    pair_id = 1000

    while len(pairs) < target_count:
        for cat in CATEGORIES:
            for prompt_t, chosen_t, rejected_t in cat["templates"]:
                order_id = random.randint(100000, 999999)
                days = random.randint(2, 7)
                amount = random.choice([450, 1200, 2990, 5400, 8900, 15400])
                bonus = random.choice([200, 300, 500, 750])

                p = prompt_t.format(order_id=order_id, days=days, amount=amount, bonus=bonus)
                c = chosen_t.format(order_id=order_id, days=days, amount=amount, bonus=bonus)
                r = rejected_t.format(order_id=order_id, days=days, amount=amount, bonus=bonus)

                # Add slight stylistic variations
                if random.random() < 0.3:
                    p = "Здравствуйте! " + p
                if random.random() < 0.2:
                    p = p + " Помогите, пожалуйста решить вопрос срочно."

                pairs.append({
                    "prompt": p,
                    "chosen": c,
                    "rejected": r
                })

                if len(pairs) >= target_count:
                    break
            if len(pairs) >= target_count:
                break

    # Shuffle deterministically
    random.shuffle(pairs)
    return pairs[:target_count]


def main():
    target_dir = Path(__file__).parent.parent / "data"
    target_dir.mkdir(parents=True, exist_ok=True)

    train_path = target_dir / "train.jsonl"
    eval_path = target_dir / "eval.jsonl"

    dataset = generate_pairs(500)
    train_split = dataset[:450]
    eval_split = dataset[450:]

    with open(train_path, "w", encoding="utf-8") as f:
        for row in train_split:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    with open(eval_path, "w", encoding="utf-8") as f:
        for row in eval_split:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")

    # Hashes
    train_hash = hashlib.sha256(train_path.read_bytes()).hexdigest()
    eval_hash = hashlib.sha256(eval_path.read_bytes()).hexdigest()

    print(f"Generated 500 preference pairs:")
    print(f"  * Train set ({len(train_split)} pairs): {train_path} (SHA-256: {train_hash})")
    print(f"  * Eval set  ({len(eval_split)} pairs):  {eval_path} (SHA-256: {eval_hash})")


if __name__ == "__main__":
    main()
